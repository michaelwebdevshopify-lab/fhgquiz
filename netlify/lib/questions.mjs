// Fisher–Yates shuffle (returns a new array).
function shuffle(arr) {
  const a = arr.slice();
  for (let n = a.length - 1; n > 0; n--) {
    const j = Math.floor(Math.random() * (n + 1));
    [a[n], a[j]] = [a[j], a[n]];
  }
  return a;
}

// A fresh random layout for one attempt:
// order[k]     = original question index shown at position k
// optOrder[k]  = original option indices, in the order shown at position k
export function makeLayout() {
  const order = shuffle(QUIZ.questions.map((_, k) => k));
  const optOrder = order.map((qi) => shuffle(QUIZ.questions[qi].options.map((_, n) => n)));
  return { order, optOrder };
}

// Questions as a participant sees them (shuffled, no answers).
export function publicQuestions(layout) {
  return layout.order.map((qi, k) => {
    const q = QUIZ.questions[qi];
    return { q: q.q, options: layout.optOrder[k].map((n) => q.options[n]), multi: Array.isArray(q.answer) };
  });
}

// Convert answers given in shuffled positions back to original question/option indices.
export function unshuffleAnswers(raw, layout) {
  const list = Array.isArray(raw) ? raw : [];
  const out = Array(QUIZ.questions.length).fill(null);
  layout.order.forEach((qi, k) => {
    const map = layout.optOrder[k];
    const v = list[k];
    const conv = (x) => (Number.isInteger(+x) && +x >= 0 && +x < map.length ? map[+x] : null);
    out[qi] = Array.isArray(v) ? v.map(conv).filter((x) => x != null) : v == null ? null : conv(v);
  });
  return normalizeAnswers(out);
}

// Clean answers (original indices) into valid values.
export function normalizeAnswers(raw) {
  const list = Array.isArray(raw) ? raw : [];
  return QUIZ.questions.map((q, k) => {
    const v = list[k];
    const valid = (n) => Number.isInteger(n) && n >= 0 && n < q.options.length;
    if (Array.isArray(q.answer)) {
      const arr = Array.isArray(v) ? v : v == null ? [] : [v];
      return [...new Set(arr.map(Number).filter(valid))].sort((x, y) => x - y);
    }
    const n = Number(v);
    return v == null || v === "" || !valid(n) ? null : n;
  });
}

export function isCorrect(given, answer) {
  if (Array.isArray(answer)) {
    return Array.isArray(given) && given.length === answer.length && given.every((v) => answer.includes(v));
  }
  return given === answer;
}

export function score(answers) {
  const results = QUIZ.questions.map((q, k) => isCorrect(answers[k], q.answer));
  const correct = results.filter(Boolean).length;
  const total = QUIZ.questions.length;
  const percent = Math.round((correct / total) * 100);
  return { results, correct, total, percent, passed: percent >= QUIZ.passMark };
}
